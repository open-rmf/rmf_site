use crate::interaction::IntersectGroundPlaneParams;
use crate::site::{AnchorBundle, ChangeDependent, Dependents};
use bevy::prelude::*;
use rmf_site_format::{Edge, Path, SiteID};
use rmf_site_picking::{Hovered, Hovering, Selectable, Selected};

/// Insert an anchor that splits whatever edge or floor-path segment the cursor
/// is hovering over. An edge A->B becomes A->C and C->B (the second segment
/// keeps all of the original edge's properties). A floor path has the new
/// anchor inserted into the nearest segment. Triggered by Ctrl + left click,
/// per https://github.com/open-rmf/rmf_site/issues/62
pub fn handle_split_on_ctrl_click(
    keyboard: Res<ButtonInput<KeyCode>>,
    mouse: Res<ButtonInput<MouseButton>>,
    hovering: Res<Hovering>,
    ground: IntersectGroundPlaneParams,
    transforms: Query<&GlobalTransform>,
    parents: Query<&ChildOf>,
    mut edges: Query<&mut Edge<Entity>>,
    mut paths: Query<&mut Path<Entity>>,
    mut commands: Commands,
) {
    let ctrl =
        keyboard.pressed(KeyCode::ControlLeft) || keyboard.pressed(KeyCode::ControlRight);
    if !ctrl || !mouse.just_pressed(MouseButton::Left) {
        return;
    }

    let Some(hovered) = hovering.0 else {
        return;
    };

    let Some(click_tf) = ground.ground_plane_intersection() else {
        return;
    };
    let click = click_tf.translation;

    // Floor (path) takes priority. Clone the Vec so the immutable borrow of
    // `paths` ends before we need the mutable borrow further down.
    if let Ok(path) = paths.get(hovered).map(|p| p.0.clone()) {
        split_path(
            hovered,
            path,
            click,
            &transforms,
            &parents,
            &mut paths,
            &mut commands,
        );
        return;
    }

    // Otherwise, is it a two-anchor edge (lane / wall / measurement / door)?
    if let Ok(edge) = edges.get(hovered).map(|e| *e) {
        split_edge(
            hovered,
            edge,
            click,
            &transforms,
            &parents,
            &mut edges,
            &mut commands,
        );
    }
}

fn split_edge(
    edge_entity: Entity,
    edge: Edge<Entity>,
    click: Vec3,
    transforms: &Query<&GlobalTransform>,
    parents: &Query<&ChildOf>,
    edges: &mut Query<&mut Edge<Entity>>,
    commands: &mut Commands,
) {
    let a = edge.start();
    let b = edge.end();
    let (Ok(a_tf), Ok(b_tf)) = (transforms.get(a), transforms.get(b)) else {
        return;
    };

    let proj = project_point_to_segment(click, a_tf.translation(), b_tf.translation());

    // Put the new anchor in the same container as the anchors it is splitting.
    let Ok(parent) = parents.get(a).map(|c| c.parent()) else {
        warn!("Unable to split edge {edge_entity:?}: its anchors have no parent");
        return;
    };

    let new_anchor = commands
        .spawn((AnchorBundle::new([proj.x, proj.y].into()), ChildOf(parent)))
        .id();

    // Second segment C->B: clone every property of the original edge, then
    // override the anchors. Identity / relationship / interaction components are
    // denied so the clone gets fresh ones (its meshes are regenerated by the
    // Added<..Marker> visual systems).
    let new_edge = commands
        .entity(edge_entity)
        .clone_and_spawn_with(|builder| {
            builder
                .deny::<SiteID>()
                .deny::<Dependents>()
                .deny::<Children>()
                .deny::<Selected>()
                .deny::<Hovered>()
                .deny::<Selectable>();
        })
        .insert(Edge::new(new_anchor, b))
        .insert(Dependents::default())
        .id();
    commands.queue(ChangeDependent::add(new_anchor, new_edge));
    commands.queue(ChangeDependent::add(b, new_edge));

    // First segment A->C: keep the original entity, just move its end anchor.
    if let Ok(mut e) = edges.get_mut(edge_entity) {
        *e.end_mut() = new_anchor;
    }
    commands.queue(ChangeDependent::remove(b, edge_entity));
    commands.queue(ChangeDependent::add(new_anchor, edge_entity));
}

fn split_path(
    floor: Entity,
    path: Vec<Entity>,
    click: Vec3,
    transforms: &Query<&GlobalTransform>,
    parents: &Query<&ChildOf>,
    paths: &mut Query<&mut Path<Entity>>,
    commands: &mut Commands,
) {
    let n = path.len();
    if n < 2 {
        return;
    }

    // Floors are closed loops, so consider the wrap-around segment too. Pick the
    // segment whose closest point is nearest to the click.
    let mut best: Option<(f32, usize, Vec3)> = None;
    for i in 0..n {
        let a = path[i];
        let b = path[(i + 1) % n];
        let (Ok(a_tf), Ok(b_tf)) = (transforms.get(a), transforms.get(b)) else {
            continue;
        };
        let proj = project_point_to_segment(click, a_tf.translation(), b_tf.translation());
        let d = proj.distance_squared(click);
        if best.map_or(true, |(bd, _, _)| d < bd) {
            best = Some((d, i + 1, proj));
        }
    }
    let Some((_, insert_index, proj)) = best else {
        return;
    };

    let Ok(parent) = parents.get(path[0]).map(|c| c.parent()) else {
        warn!("Unable to split floor {floor:?}: its anchors have no parent");
        return;
    };
    let new_anchor = commands
        .spawn((AnchorBundle::new([proj.x, proj.y].into()), ChildOf(parent)))
        .id();

    if let Ok(mut p) = paths.get_mut(floor) {
        let idx = insert_index.min(p.0.len());
        p.0.insert(idx, new_anchor);
    }
    commands.queue(ChangeDependent::add(new_anchor, floor));
}

/// Closest point to `p` on the segment `[a, b]`.
fn project_point_to_segment(p: Vec3, a: Vec3, b: Vec3) -> Vec3 {
    let ab = b - a;
    let len_sq = ab.length_squared();
    if len_sq <= f32::EPSILON {
        return a;
    }
    let t = ((p - a).dot(ab) / len_sq).clamp(0.0, 1.0);
    a + ab * t
}